def next_dialog_step(session):
    """
    Определяет следующий шаг диалога.

    Логика:
    1. Если не понятна категория и нет задачи — просим уточнить товар.
    2. Если указан только бренд — уточняем, что именно показать.
    3. Если указана только задача, но нет категории — предлагаем подходящие категории.
    4. Если категория есть, но запрос слишком общий — задаём уточняющий вопрос.
    5. Если бюджет слишком маленький для категории — предупреждаем и предлагаем варианты.
    6. Если данных достаточно — запускаем поиск.
    """

    if _is_only_brand(session):
        return _build_only_brand_question(session)

    if _is_only_purpose(session):
        return _build_only_purpose_question(session)

    if not session.get("category"):
        return _build_unknown_product_question()

    if session.get("skip_clarification"):
        return {
            "action": "search"
    }

    if _is_low_budget_for_category(session):
        return _build_low_budget_question(session)

    if _is_too_broad_category_request(session):
        return _build_too_broad_question(session)

    return {
        "action": "search"
    }