def _has_value(session: dict, key: str) -> bool:
    """
    Проверяет, заполнено ли поле состояния диалога.
    """
    value = session.get(key)
    return value is not None and value != ""


def _has_any_value(session: dict, keys: list[str]) -> bool:
    """
    Проверяет, заполнено ли хотя бы одно поле из списка.
    """
    return any(_has_value(session, key) for key in keys)


def _is_only_brand(session: dict) -> bool:
    """
    Определяет ситуацию, когда пользователь указал только бренд,
    но не указал категорию товара или назначение.

    Пример:
    - Stihl
    - покажи Stihl
    - есть Champion
    """
    return (
        _has_value(session, "brand")
        and not _has_value(session, "category")
        and not _has_value(session, "purpose")
    )


def _is_only_purpose(session: dict) -> bool:
    """
    Определяет ситуацию, когда пользователь описал задачу,
    но не указал конкретный тип товара.

    Примеры:
    - нужно для дачи
    - нужно для сада
    - нужно для участка
    - надо для травы
    - нужно для полива
    """
    return (
        _has_value(session, "purpose")
        and not _has_value(session, "category")
    )


def _is_too_broad_category_request(session: dict) -> bool:
    """
    Определяет слишком общий запрос, когда категория известна,
    но нет дополнительных параметров для точного подбора.

    Если пользователь явно написал "все товары", "любые" или "без разницы",
    уточняющий вопрос не задаётся — запускается поиск по категории.
    """
    if session.get("skip_clarification"):
        return False

    if not _has_value(session, "category"):
        return False

    additional_fields = [
        "brand",
        "purpose",
        "price_segment",
        "min_price",
        "max_price",
        "power_type",
        "area_sotka",
        "excluded_brand",
        "excluded_power_type",
    ]

    return not _has_any_value(session, additional_fields)


def _is_low_budget_for_category(session: dict) -> bool:
    """
    Определяет ситуацию, когда пользователь указал слишком маленький бюджет
    для выбранной категории товара.

    Это не строгие рыночные цены, а демонстрационные пороги для логики бота.
    Они нужны, чтобы бот не просто писал 'ничего не найдено',
    а объяснял пользователю, что бюджет может быть слишком низким.
    """
    category = session.get("category")
    max_price = session.get("max_price")

    if not category or max_price is None:
        return False

    min_reasonable_price = {
        "бензопила": 7000,
        "триммер": 4000,
        "газонокосилка": 12000,
        "мотоблок": 35000,
        "культиватор": 18000,
        "опрыскиватель": 1500,
        "насос": 3000,
    }

    threshold = min_reasonable_price.get(category)

    if threshold is None:
        return False

    return max_price < threshold


